package cl.nheox.quests.export

import cl.nheox.quests.BuildInfo
import cl.nheox.quests.domain.Clock
import cl.nheox.quests.domain.Dates
import cl.nheox.quests.domain.Quest
import cl.nheox.quests.domain.QuestState
import cl.nheox.quests.domain.Reminder
import cl.nheox.quests.projection.QuestsState
import java.time.ZoneOffset
import java.time.format.DateTimeFormatter

/**
 * Generates an iCalendar feed of everything with a due date.
 *
 * This is the answer to the reminder problem (§7.5), and it is the most
 * important thing in this file. Desktop notifications only fire when the
 * machine is awake and the user is near it; a focus app that deliberately puts
 * the phone out of reach makes a 3pm desktop reminder useless. So instead of
 * trying to build a notification system that can reach someone, Quests writes a
 * calendar file into the synced folder and lets the user subscribe to it from
 * whatever calendar they already trust. Alerts then arrive through an app that
 * is already allowed to interrupt them, and Quests never has to exist on the
 * phone or talk to a network.
 *
 * Deliberately RFC 5545-literal: CRLF line endings, 75-octet line folding, and
 * UTC timestamps rather than `TZID` (which would require shipping a whole
 * `VTIMEZONE` component to be legal). Calendar parsers are unforgiving, and a
 * feed that silently fails to import would take the whole reminder story with
 * it.
 */
public object IcsExport {
    private const val CRLF = "\r\n"
    private const val MAX_OCTETS = 73
    private val stampFormat = DateTimeFormatter.ofPattern("yyyyMMdd'T'HHmmss'Z'")
    private val dateFormat = DateTimeFormatter.ofPattern("yyyyMMdd")

    public fun render(state: QuestsState, clock: Clock, includeCompleted: Boolean = false): String {
        val lines = mutableListOf<String>()
        lines += "BEGIN:VCALENDAR"
        lines += "VERSION:2.0"
        lines += "PRODID:-//nheox//Quests ${BuildInfo.VERSION}//EN"
        lines += "CALSCALE:GREGORIAN"
        lines += "METHOD:PUBLISH"
        lines += "X-WR-CALNAME:Quests"
        lines += "X-WR-CALDESC:Quests with a due date, generated by Quests."

        val dated = state.quests.values
            .filter { it.dueDate != null }
            .filter { includeCompleted || it.state != QuestState.DONE }
            .sortedWith(compareBy({ it.dueDate }, { it.dueTime }, { it.id }))

        for (quest in dated) {
            lines += renderEvent(quest, state, clock)
        }

        lines += "END:VCALENDAR"
        return lines.flatMap { fold(it) }.joinToString(CRLF, postfix = CRLF)
    }

    private fun renderEvent(quest: Quest, state: QuestsState, clock: Clock): List<String> {
        val dueDate = quest.dueDate ?: return emptyList()
        val zone = clock.zone()
        val out = mutableListOf<String>()
        out += "BEGIN:VEVENT"
        // A stable UID per quest means a calendar updates the entry in place
        // instead of accumulating a duplicate on every refresh.
        out += "UID:${quest.id}@quests.nheox.cl"
        out += "DTSTAMP:${stampFormat.format(quest.updatedAt.atOffset(ZoneOffset.UTC))}"
        // SEQUENCE must rise whenever the event changes, or subscribers ignore it.
        out += "SEQUENCE:${quest.updatedAt.epochSecond}"

        val dueTime = quest.dueTime
        if (dueTime == null) {
            out += "DTSTART;VALUE=DATE:${dateFormat.format(dueDate)}"
            out += "DTEND;VALUE=DATE:${dateFormat.format(dueDate.plusDays(1))}"
        } else {
            val start = dueDate.atTime(dueTime).atZone(zone).toInstant()
            val minutes = (quest.estimatedMinutes ?: 30).coerceIn(5, 8 * 60)
            out += "DTSTART:${stampFormat.format(start.atOffset(ZoneOffset.UTC))}"
            out += "DTEND:${stampFormat.format(start.plusSeconds(minutes * 60L).atOffset(ZoneOffset.UTC))}"
        }

        out += "SUMMARY:${escape(summaryOf(quest))}"
        out += "DESCRIPTION:${escape(descriptionOf(quest, state))}"
        out += "STATUS:" + when (quest.state) {
            QuestState.OPEN -> "CONFIRMED"
            QuestState.DONE -> "COMPLETED"
            QuestState.FAILED -> "CANCELLED"
        }
        out += "PRIORITY:${priorityOf(quest)}"

        val categories = state.skillsOf(quest).map { it.name }
        if (categories.isNotEmpty()) {
            out += "CATEGORIES:" + categories.joinToString(",") { escape(it) }
        }

        if (quest.state == QuestState.OPEN) {
            for (reminder in quest.reminders) {
                // Added as separate lines, never as one joined block: folding
                // runs per content line, and a multi-line string handed to it
                // gets folded straight through its own line breaks — which is
                // how `TRIGGER:-PT30M` becomes `TRIGGE` + `R:-PT30M`.
                out += renderAlarm(reminder, quest, zone)
            }
        }

        out += "END:VEVENT"
        return out.filter { it.isNotEmpty() }
    }

    private fun renderAlarm(reminder: Reminder, quest: Quest, zone: java.time.ZoneId): List<String> = listOf(
        "BEGIN:VALARM",
        "ACTION:DISPLAY",
        "DESCRIPTION:${escape(quest.title)}",
        when (reminder) {
            is Reminder.BeforeDue -> "TRIGGER:-PT${reminder.minutesBefore}M"
            is Reminder.At -> "TRIGGER;VALUE=DATE-TIME:" + stampFormat.format(
                reminder.date.atTime(reminder.time).atZone(zone).toInstant().atOffset(ZoneOffset.UTC),
            )
        },
        "END:VALARM",
    )

    private fun summaryOf(quest: Quest): String {
        val marker = when (quest.state) {
            QuestState.OPEN -> ""
            QuestState.DONE -> "✓ "
            QuestState.FAILED -> "✗ "
        }
        return marker + quest.title
    }

    private fun descriptionOf(quest: Quest, state: QuestsState): String = buildString {
        if (quest.notes.isNotBlank()) {
            append(quest.notes.trim())
            append("\n\n")
        }
        append("Difficulty: ${label(quest.difficulty.name)}")
        append("\nFear: ${label(quest.fear.name)}")
        append("\nUrgency: ${label(quest.urgency.name)}")
        quest.estimatedMinutes?.let { append("\nEstimate: ${Dates.formatMinutes(it)}") }
        append("\nXP on completion: ${quest.projectedXp()}")
        val skills = state.skillsOf(quest)
        if (skills.isNotEmpty()) {
            append("\nSkills: ${skills.joinToString(", ") { it.name }}")
        }
        quest.repetition?.let { append("\nRepeats: every ${it.every} ${it.unit.name.lowercase()}") }
    }

    /** iCalendar priority runs 1 (highest) to 9 (lowest); 0 means unset. */
    private fun priorityOf(quest: Quest): Int = when (quest.urgency.index) {
        4 -> 1
        3 -> 3
        2 -> 5
        1 -> 7
        else -> 9
    }

    private fun label(enumName: String): String = enumName.lowercase()
        .split('_')
        .joinToString(" ") { part -> part.replaceFirstChar { it.uppercase() } }

    internal fun escape(text: String): String = text
        .replace("\\", "\\\\")
        .replace(";", "\\;")
        .replace(",", "\\,")
        .replace("\r\n", "\\n")
        .replace("\n", "\\n")
        .replace("\r", "\\n")

    /**
     * Folds a content line to 75 octets, continuing with a leading space.
     *
     * Counted in UTF-8 bytes, not characters, and never splitting a multi-byte
     * sequence — otherwise an accented quest title would produce an invalid
     * feed, which is exactly the sort of bug that would go unnoticed in English
     * and break immediately in Spanish.
     */
    internal fun fold(line: String): List<String> {
        val bytes = line.toByteArray(Charsets.UTF_8)
        if (bytes.size <= MAX_OCTETS + 2) return listOf(line)

        val out = mutableListOf<String>()
        var current = StringBuilder()
        var currentBytes = 0
        var first = true

        for (codePoint in line.codePoints()) {
            val chunk = String(Character.toChars(codePoint))
            val size = chunk.toByteArray(Charsets.UTF_8).size
            val limit = if (first) MAX_OCTETS + 2 else MAX_OCTETS
            if (currentBytes + size > limit) {
                out += if (first) current.toString() else " $current"
                first = false
                current = StringBuilder()
                currentBytes = 0
            }
            current.append(chunk)
            currentBytes += size
        }
        if (current.isNotEmpty()) out += if (first) current.toString() else " $current"
        return out
    }
}

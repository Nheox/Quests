/**
 * Finishes the `.deb` that jpackage produces.
 *
 * Three things jpackage does not do, each of which matters:
 *
 *  1. **`/usr/bin/quests`.** jpackage installs under `/opt/quests` and never
 *     puts the launcher on `PATH`. Without that symlink `quests --capture` does
 *     not resolve — and since a desktop keybinding runs exactly that command,
 *     global quick capture (§8.3) would be broken for anyone installing from the
 *     package.
 *  2. **A desktop entry in the standard location.** jpackage leaves its
 *     generated `.desktop` inside `/opt`. Debian convention is to ship the file
 *     in `/usr/share/applications`, and ours additionally declares a *Quick
 *     capture* action.
 *  3. **No second menu entry.** jpackage also registers its generated
 *     `.desktop` from `postinst` with `xdg-desktop-menu`, so alongside ours the
 *     application menu showed Quests twice. Those calls are removed from
 *     `postinst` and `prerm` alike, which also means a machine with no writable
 *     menu directory — a container, a chroot, a minimal server — can no longer
 *     fail the install or the removal over a menu entry. Upgrading from a
 *     package that registered the duplicate still clears it, because on
 *     upgrade it is the old package's `prerm` that runs.
 *
 * The Compose plugin exposes no hook for any of this, so the package is
 * unpacked, corrected and rebuilt.
 */
abstract class FinalizeDebPackage : DefaultTask() {
    @get:InputDirectory
    abstract val debDirectory: DirectoryProperty

    @get:InputFile
    abstract val desktopEntry: RegularFileProperty

    @get:InputFiles
    abstract val icons: ConfigurableFileCollection

    @get:Input
    abstract val commandName: Property<String>

    @get:Input
    abstract val launcherTarget: Property<String>

    @get:Inject
    abstract val exec: ExecOperations

    @TaskAction
    fun finalize() {
        val packages = debDirectory.get().asFile.listFiles { file -> file.extension == "deb" }.orEmpty()
        if (packages.isEmpty()) {
            logger.lifecycle("No .deb to post-process.")
            return
        }

        // fakeroot keeps the repacked archive owned by root:root, which is what
        // dpkg expects; without it every path carries the builder's uid.
        val hasFakeroot = exec.exec {
            commandLine("sh", "-c", "command -v fakeroot")
            isIgnoreExitValue = true
            standardOutput = ByteArrayOutputStream()
        }.exitValue == 0

        packages.forEach { archive ->
            val staging = temporaryDir.resolve(archive.nameWithoutExtension)
            staging.deleteRecursively()
            exec.exec { commandLine("dpkg-deb", "-R", archive.absolutePath, staging.absolutePath) }

            addLauncherSymlink(staging)
            addDesktopEntry(staging)
            addIcons(staging)
            removeGeneratedMenuEntry(staging)

            val build = listOf("dpkg-deb", "--build", staging.absolutePath, archive.absolutePath)
            exec.exec { commandLine(if (hasFakeroot) listOf("fakeroot") + build else build) }
            logger.lifecycle("Finalised ${archive.name}")
        }
    }

    private fun addLauncherSymlink(staging: File) {
        val binDir = staging.resolve("usr/bin").apply { mkdirs() }
        val link = binDir.resolve(commandName.get()).toPath()
        Files.deleteIfExists(link)
        Files.createSymbolicLink(link, Path.of(launcherTarget.get()))
    }

    private fun addDesktopEntry(staging: File) {
        val target = staging.resolve("usr/share/applications/${commandName.get()}.desktop")
        target.parentFile.mkdirs()
        desktopEntry.get().asFile.copyTo(target, overwrite = true)
    }

    private fun addIcons(staging: File) {
        icons.files.forEach { icon ->
            // quests-48.png installs at 48x48; plain quests.png is the 512 master.
            val size = Regex("""quests-(\d+)\.png""").find(icon.name)?.groupValues?.get(1) ?: "512"
            val target = staging.resolve("usr/share/icons/hicolor/${size}x$size/apps/${commandName.get()}.png")
            target.parentFile.mkdirs()
            icon.copyTo(target, overwrite = true)
        }
    }

    private fun removeGeneratedMenuEntry(staging: File) {
        listOf("postinst", "prerm").forEach { name ->
            val script = staging.resolve("DEBIAN/$name")
            if (!script.isFile) return@forEach
            val kept = script.readLines().filterNot { it.trimStart().startsWith("xdg-desktop-menu") }
            script.writeText(kept.joinToString("\n") + "\n")
            script.setExecutable(true)
        }
    }
}

val finalizeDebPackage by tasks.registering(FinalizeDebPackage::class) {
    debDirectory.set(layout.buildDirectory.dir("compose/binaries/main/deb"))
    desktopEntry.set(rootProject.file("packaging/deb/quests.desktop"))
    icons.from(
        project.fileTree("src/desktopMain/resources/icons") {
            include("quests-*.png")
            include("quests.png")
            // The tray marks share the prefix but are not app icons: addIcons
            // would read no size from their names and install one over the
            // 512x512 icon.
            exclude("quests-tray-*.png")
        },
    )
    commandName.set("quests")
    launcherTarget.set("/opt/quests/bin/Quests")
}

tasks.matching { it.name == "packageDeb" }.configureEach {
    finalizedBy(finalizeDebPackage)
}

